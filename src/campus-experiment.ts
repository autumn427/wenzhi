export function campusRouteExperiment(run: UniverseRun) {
  const last = run.decisions[run.decisions.length - 1]
  const name = { A: '问清一份兼职的条件', B: '为一个真实实习岗位准备一段经历', C: '和朋友算清第一摊的账' }[run.code]
  return {
    origin: { kind: 'route' as const, code: run.code }, title: name,
    hypothesis: `从“${last.choiceLabel}”出发，用一周${name}，看看能否放进自己的课表。`,
    reason: `你走到了“${run.currentEvent.title}”，最后的取舍是“${last.tradeoff}”。这周先核实条件，故事里的结果还没有在现实发生。`,
    dailyTasks: tasks[run.code].map((task, index) => ({ day: index + 1, title: titles[run.code][index], minutes: [10, 10, 20, 10, 20, 10, 10][index], task })),
    successSignal: '留下一份真实条件记录，明确可投入的时间和一项不能接受的条件；没有得到回复也如实记录。',
    stopRule: '全周最多 90 分钟用于了解和准备；需要占用课程、影响小组作业或超出预算时暂停，本周不预付费用、不采购囤货。',
    feedbackQuestion: '哪条实际回复或记录让你更想试、想缩小范围或决定不做？还有什么没问清？',
  }
}

